def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description="Build targeted Chinese refinement seed samples.")
    parser.add_argument("--out", required=True)
    parser.add_argument("--ms-swift-out", required=True)
    return parser.parse_args()


def write_jsonl(path: Path, records: list[dict[str, Any]]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", encoding="utf-8") as handle:
        for record in records:
            handle.write(json.dumps(record, ensure_ascii=False) + "\n")


def main() -> None:
    args = parse_args()
    preference_records: list[dict[str, Any]] = []
    sft_records: list[dict[str, Any]] = []
    seen: set[tuple[str, str]] = set()

    for index, sample in enumerate([*SAMPLES, *BOUNDARY_CALIBRATION_SAMPLES], start=1):
        user = str(sample["user"]).strip()
        assistant = str(sample["assistant"]).strip()
        key = (user, assistant)
        if key in seen:
            continue
        seen.add(key)
        record = {
            "id": f"targeted_refinement_{index:04d}",
            "task_type": "targeted_refinement",
            "language": "zh",
            "category": sample["category"],
            "prompt": [{"role": "user", "content": user}],
            "chosen": assistant,
            "rejected": "",
            "meta": {"source": "handcrafted_targeted_seed_20260511"},
        }
        preference_records.append(record)
        sft_records.append(
            {
                "messages": [*record["prompt"], {"role": "assistant", "content": assistant}],
                "meta": {
                    "source": "handcrafted_targeted_seed_20260511",
                    "category": sample["category"],
                },
            }
        )

    write_jsonl(Path(args.out), preference_records)
    write_jsonl(Path(args.ms_swift_out), sft_records)
    counts = Counter(record["category"] for record in preference_records)
    print(
        json.dumps(
            {
                "out": args.out,
                "ms_swift_out": args.ms_swift_out,
                "records": len(preference_records),
                "category_counts": dict(counts),
            },
            ensure_ascii=False,
            indent=2,
        )
    )


if __name__ == "__main__":
    main()
